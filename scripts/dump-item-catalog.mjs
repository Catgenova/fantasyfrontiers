// Regenerate supabase/seeds/item_catalog_seed.sql from the client's item registries.
//
// The server's item_catalog table is the item-key ALLOWLIST: it gates the item ledger (item_sync only
// credits catalogued keys, so a tampered client can't mint a fake item into the ledger) and the
// marketplace (only `tradeable` keys can be listed/bid), which is what blocks buy/sell orders on made-up
// items. It MUST mirror the client's inventory-key universe exactly, or a legit item would be un-ledgerable.
// This dumps __FF.buildItemCatalog() from a headless load of index.html and writes the canonical seed.
// Run it after any item change, then re-run the seed in the Supabase SQL editor. CI runs it with --check.
//
//   node scripts/dump-item-catalog.mjs           # rewrite the seed
//   node scripts/dump-item-catalog.mjs --check    # exit 1 if the committed seed differs from a fresh dump
//
// Uses the same puppeteer harness as scripts/dump-recipes.mjs (Chromium bundled in tests/node_modules).
import http from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SEED = join(ROOT, 'supabase', 'seeds', 'item_catalog_seed.sql');
const MIME = { '.html': 'text/html', '.js': 'application/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml' };

// Build the seed SQL from the catalog map { item_key: 1|0 } (1 = market-tradeable, 0 = ledger-only). MUST
// stay byte-identical to any other generator so the CI --check diff is meaningful. Exported so a local
// generator (e.g. a Playwright one-off where puppeteer isn't installed) can produce the same bytes.
export function seedSql(catalog) {
  const esc = (s) => String(s).replace(/'/g, "''");
  const keys = Object.keys(catalog).sort();
  const rows = keys.map((k) => `('${esc(k)}',${catalog[k] ? 'true' : 'false'})`);
  const tradeable = keys.filter((k) => catalog[k]).length;
  return '-- GENERATED by buildItemCatalog() -- DO NOT EDIT BY HAND. Regenerate via scripts/dump-item-catalog.\n'
    + `-- Server item-key allowlist (market-tradeable flag). ${keys.length} items, ${tradeable} tradeable.\n`
    + 'begin;\n'
    + 'truncate table public.item_catalog;\n'
    + 'insert into public.item_catalog (item_key, tradeable) values\n'
    + rows.join(',\n') + ';\n'
    + 'commit;\n';
}

// Run as a script (not when imported for seedSql).
if (import.meta.url === `file://${process.argv[1]}`) {
  const require = createRequire(join(ROOT, 'tests', 'package.json'));
  const puppeteer = require('puppeteer');

  const server = http.createServer(async (req, res) => {
    try {
      let p = decodeURIComponent((req.url || '/').split('?')[0]);
      if (p === '/') p = '/index.html';
      const file = normalize(join(ROOT, p));
      if (!file.startsWith(normalize(ROOT))) { res.statusCode = 403; return res.end('forbidden'); }
      res.setHeader('Content-Type', MIME[extname(file).toLowerCase()] || 'application/octet-stream');
      res.end(await readFile(file));
    } catch { res.statusCode = 404; res.end('not found'); }
  });
  await new Promise((r) => server.listen(0, r));
  const port = server.address().port;

  const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox', '--disable-setuid-sandbox'] });
  let exitCode = 0;
  try {
    const page = await browser.newPage();
    page.on('pageerror', (e) => console.log('PAGEERROR:', e.message));
    await page.goto(`http://localhost:${port}/index.html?selftest`, { waitUntil: 'domcontentloaded', timeout: 30000 });
    await page.waitForFunction('window.__FF && typeof window.__FF.buildItemCatalog === "function"', { timeout: 30000 });
    const catalog = await page.evaluate(() => window.__FF.buildItemCatalog());
    const sql = seedSql(catalog);
    const check = process.argv.includes('--check');
    if (check) {
      let current = '';
      try { current = await readFile(SEED, 'utf8'); } catch {}
      if (current.replace(/\r\n/g, '\n') !== sql) {
        console.error('item_catalog seed is STALE. Run `node scripts/dump-item-catalog.mjs` and commit + re-run the seed SQL.');
        exitCode = 1;
      } else {
        console.log(`item_catalog seed is up to date (${Object.keys(catalog).length} items).`);
      }
    } else {
      await writeFile(SEED, sql);
      console.log(`Wrote ${SEED} (${Object.keys(catalog).length} items).`);
    }
  } catch (e) {
    console.error('dump-item-catalog error:', e.message); exitCode = 1;
  } finally {
    await browser.close();
    server.close();
  }
  process.exit(exitCode);
}
